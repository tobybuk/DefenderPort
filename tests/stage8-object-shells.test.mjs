test('GETSHL exactly allocates from original free object list and links SPTR with source record fields', () => {
    const { r, v, p, w16, obj } = f();
    const shooter = p.GETOB(), owner = a('PTAB');
    r.write16(obj(shooter, 'OX16'), 0x1200);
    r.write16(obj(shooter, 'OY16'), 0x8000);
    const originalFree = r.read16(a('OFREE'));
    const shell = createDefa7ShellRoutines(r, L, v);
    const X = shell.GETSHL(shooter, owner, { OBJCOL: 0xd222, OPICT: 0xe444, OCVECT: 0xd555 });
    assert.equal(X, originalFree);
    assert.equal(r.read16(a('SPTR')), X);
    assert.equal(r.read16(obj(X, 'OBJX')), 0x4880);
    assert.equal(r.read16(obj(X, 'OX16')), 0x4880);
    assert.equal(r.read16(obj(X, 'OY16')), 0x8048);
    assert.equal(r.read16(obj(X, 'OBJID')), owner);
    assert.equal(r.read16(obj(X, 'OBJCOL')), 0xd222);
    assert.equal(r.read16(obj(X, 'OPICT')), 0xe444);
    assert.equal(r.read16(obj(X, 'OCVECT')), 0xd555);
    assert.equal(r.read16(obj(X, 'OXV')), 0);
    assert.equal(r.read16(obj(X, 'OYV')), 0);
    assert.equal(r.read8(obj(X, 'ODATA')), 20);
    assert.equal(r.read8(obj(X, 'ODATA') + 1), 20);
    assert.equal(r.read8(a('BMBCNT')), 1);
    assert.notEqual(r.read16(a('OFREE')), X);
});
test('GETSHL rejects offscreen, low Y, shell count cap and missing inline descriptor without consuming OFREE', () => {
    const { r, v, p, w16, obj } = f();
    const shooter = p.GETOB();
    const shell = createDefa7ShellRoutines(r, L, v);
    const d = { OBJCOL: 1, OPICT: 2, OCVECT: 3 };
    r.write16(obj(shooter, 'OX16'), 150 * 64);
    r.write16(obj(shooter, 'OY16'), 0x8000);
    const oldFree = r.read16(a('OFREE'));
    assert.equal(shell.GETSHL(shooter, 0, d), null);
    r.write16(obj(shooter, 'OX16'), 0x1000);
    r.write16(obj(shooter, 'OY16'), 0x2a00);
    assert.equal(shell.GETSHL(shooter, 0, d), null);
    r.write16(obj(shooter, 'OY16'), 0x2b00);
    r.write8(a('BMBCNT'), 20);
    assert.equal(shell.GETSHL(shooter, 0, d), null);
    assert.equal(r.read16(a('OFREE')), oldFree);
    assert.throws(() => shell.GETSHL(shooter, 0), /original three-word/);
});
