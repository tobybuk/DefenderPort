test('OPROC traverses source linked objects and rejects unresolved picture descriptors', () => {
    const { r, p, w16, obj } = f(), calls = [];
    const X = p.GETOB(), Y = p.GETOB();
    w16('OPTR', Y);
    r.write16(Y, X);
    for (const [k, ptr] of [[X, 0x1000], [Y, 0x2000]]) {
        r.write16(obj(k, 'OPICT'), ptr);
        r.write8(obj(k, 'OY16'), 0x70);
        r.write16(obj(k, 'OX16'), 0x0800);
    }
    const o = createDefa7ObjectProcessRoutines(r, L, { resolvePicture: () => descriptor(calls) });
    o.OPROC(0xff2a);
    assert.deepEqual(calls.map(e => e[3]), [Y, X]);
    r.write16(obj(Y, 'OPICT'), 0xffff);
    assert.throws(() => createDefa7ObjectProcessRoutines(r, L).OPROC(0xff2a), /unresolved original picture/);
});
test('FISS translates two successive source LSRA carry bits into original table bytes', () => {
    const { r } = f();
    const values = [0, 1, 2, 3, 255, 128, 0x55, 0xaa];
    let n = 0;
    const { FISS } = createDefa7FireTableRoutines(r, L, { RAND: () => values[n++ % values.length] });
    FISS();
    assert.equal(r.read16(a('FISX')), a('FISTAB'));
    assert.deepEqual([...r.snapshot(a('FISTAB'), a('FISTAB') + 8)], [0, 1, 16, 17, 17, 0, 1, 16]);
});
