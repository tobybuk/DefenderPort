test('BMBOUT copies two source fireball columns with upper/lower video nibbles untouched', () => {
    const { r, v, obj } = f();
    const X = a('OLIST');
    r.write16(a('BAX'), a('FBTAB'));
    for (let i = 0; i < 12; i++)
        r.write8(a('FBTAB') + i, 0x40 + i);
    r.write16(obj(X, 'OBJX'), 0x3060);
    const shells = createDefa7ShellRoutines(r, L, v);
    v.write8(0x1060, 255);
    shells.BMBOUT(X, 0x1060);
    assert.equal(v.read8(0x1060), 0);
    assert.deepEqual([0, 1, 2, 0x100, 0x101, 0x102].map(n => v.read8(0x3060 + n)), [0x40, 0x41, 0x42, 0x43, 0x44, 0x45]);
    r.write16(obj(X, 'OX16'), 0x0080);
    shells.BMBOUT(X, 0x1060);
    assert.equal(v.read8(0x3060), 0x46);
});
