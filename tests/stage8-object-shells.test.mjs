test('SHSCAN removes dead or expiring shells, links original OFREE, decrements BMBCNT', () => {
    const { r, v, p, w16, obj } = f(), cleared = [];
    const X = p.GETOB(), Y = p.GETOB();
    w16('SPTR', Y);
    r.write16(Y, X);
    r.write8(obj(Y, 'ODATA'), 2);
    r.write8(obj(Y, 'ODATA') + 1, 1);
    r.write8(obj(X, 'ODATA'), 1);
    r.write8(obj(X, 'ODATA') + 1, 1);
    r.write8(a('BMBCNT'), 2);
    const shell = createDefa7ShellRoutines(r, L, v, { OFSHIT: x => cleared.push(x) });
    shell.SHSCAN();
    assert.equal(r.read16(a('SPTR')), Y);
    assert.equal(r.read8(obj(Y, 'ODATA')), 1);
    assert.deepEqual(cleared, [X]);
    assert.equal(r.read8(a('BMBCNT')), 1);
    assert.equal(r.read16(a('OFREE')), X);
    shell.SHSCAN();
    assert.equal(r.read16(a('SPTR')), 0);
    assert.deepEqual(cleared, [X, Y]);
    assert.equal(r.read8(a('BMBCNT')), 0);
});
