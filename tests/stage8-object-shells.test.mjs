const a = n => L.at(n);
const f = () => {
    const r = new RAM(), v = new VideoMemory(), p = createDefa7Routines(r, L);
    p.OINIT();
    const r16 = n => r.read16(a(n)), w16 = (n, x) => r.write16(a(n), x);
    const obj = (X, n) => X + a(n);
    return { r, v, p, r16, w16, obj };
};
const descriptor = (calls, width = 6) => ({ OBJW: width, OBJDEL: (...args) => calls.push(['erase', ...args]), OBJWRT: (...args) => calls.push(['draw', ...args]) });
test('OPROC draws in source 150*64 world viewport using 4x shifted X and exact Y byte', () => {
    const { r, p, w16, obj } = f(), calls = [];
    const X = p.GETOB();
    w16('OPTR', X);
    r.write16(obj(X, 'OPICT'), 0xc123);
    r.write16(obj(X, 'OX16'), 0x0800);
    r.write8(obj(X, 'OY16'), 0x80);
    w16('BGL', 0);
    const o = createDefa7ObjectProcessRoutines(r, L, { resolvePicture: y => y === 0xc123 ? descriptor(calls) : null });
    o.OPROC(0xef2a);
    assert.deepEqual(calls, [['draw', 0x2080, 0xc123, X, false]]);
    assert.equal(r.read16(obj(X, 'OBJX')), 0x2080);
});
