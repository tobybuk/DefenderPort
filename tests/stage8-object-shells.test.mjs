test('FISS and FBINIT require translated RAND, not Math.random', () => {
    const { r } = f();
    const x = createDefa7FireTableRoutines(r, L);
    assert.throws(() => x.FISS(), /original RAND/);
    assert.throws(() => x.FBINIT(), /original RAND/);
    const seed = createDefa7RandomRoutines(r, L);
    r.write16(a('HSEED'), 0xa55a);
    const genuine = createDefa7FireTableRoutines(r, L, { RAND: seed.RAND });
    genuine.FISS();
    genuine.FBINIT();
    assert.ok([...r.snapshot(a('FBTAB'), a('FBTEND'))].some(n => n !== 0));
});
test('SHELL updates original 16-bit positions and dispatches through OBJCOL pointer', () => {
    const { r, v, p, w16, obj } = f(), events = [];
    const X = p.GETOB();
    w16('SPTR', X);
    r.write16(obj(X, 'OBJCOL'), 0xd000);
    r.write16(obj(X, 'OBJX'), 0x4080);
    r.write16(obj(X, 'OX16'), 0x4000);
    r.write16(obj(X, 'OY16'), 0x8000);
    r.write16(obj(X, 'OXV'), 0x0100);
    r.write16(obj(X, 'OYV'), 0x0100);
    w16('BGLX', 0);
    w16('BGL', 0);
    const shells = createDefa7ShellRoutines(r, L, v, { resolveOutput: p => p === 0xd000 ? (...args) => events.push(args) : null });
    shells.SHELL();
    assert.equal(r.read16(obj(X, 'OBJX')), 0x4181);
    assert.equal(r.read16(obj(X, 'OX16')), 0x4100);
    assert.equal(r.read16(obj(X, 'OY16')), 0x8100);
    assert.deepEqual(events, [[X, 0x4080]]);
});
