/**
 * Original DEFB6.SRC 2185-2219, pinned e74006344b16d19245510b5e55780f90d7606bb8.
 * FDB words are columns of (high byte,low byte) raster pairs.
 * Native picture data; never HTML/Canvas sprites.
 */
function columns(words, width, height) {
    if (words.length * 2 !== width * height)
        throw Error('Source FDB width/height mismatch');
    const data = new Uint8Array(words.length * 2);
    for (let i = 0; i < words.length; i++) {
        data[i * 2] = words[i] >>> 8;
        data[i * 2 + 1] = words[i] & 255;
    }
    return data;
}
function descriptor(width, height, phase0, phase1 = phase0) {
    return Object.freeze({ width, height, phases: [columns(phase0, width, height), columns(phase1, width, height)] });
}
